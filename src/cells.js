// Позиция клетки на доске в процентах (0..100)
export function getCellPosition(n) {
  if (n <= 0) return { x: -10, y: -10 }
  const row = Math.floor((n - 1) / 8)
  const colInRow = (n - 1) % 8
  const col = row % 2 === 0 ? colInRow : 7 - colInRow
  return {
    x: ((col + 0.5) / 8) * 100,
    y: 100 - ((row + 0.5) / 9) * 100
  }
}