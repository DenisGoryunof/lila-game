// Центр клетки в координатах SVG (viewBox 900×800)
// 9 столбцов × 8 рядов, зигзаг, клетка 72 в левом верхнем углу
export function cellCenter(n) {
  const row = Math.floor((n - 1) / 9)          // 0..7 (0 — нижний ряд)
  const colInRow = (n - 1) % 9                 // 0..8
  const col = row % 2 === 0 ? colInRow : 8 - colInRow
  return {
    x: (col + 0.5) * 100,   // 50..850
    y: (7.5 - row) * 100    // 750..50
  }
}

// Волнистая линия для змеи: от головы (from) к хвосту (to)
export function buildSnakePoints(from, to, samples) {
  const p1 = cellCenter(from)
  const p2 = cellCenter(to)
  const dx = p2.x - p1.x
  const dy = p2.y - p1.y
  const dist = Math.hypot(dx, dy) || 1
  const nx = -dy / dist
  const ny = dx / dist
  const amplitude = Math.min(42, dist / 7)
  const waves = Math.max(2, Math.round(dist / 180))

  const N = samples || Math.max(50, Math.round(dist / 12))
  const points = []
  for (let i = 0; i <= N; i++) {
    const t = i / N
    const envelope = Math.sin(t * Math.PI)
    const wave = Math.sin(t * Math.PI * 2 * waves) * amplitude * envelope
    points.push({
      x: p1.x + dx * t + nx * wave,
      y: p1.y + dy * t + ny * wave
    })
  }
  return points
}

export function buildArrowPoints(from, to, samples = 24) {
  const p1 = cellCenter(from)
  const p2 = cellCenter(to)
  const points = []
  for (let i = 0; i <= samples; i++) {
    const t = i / samples
    points.push({
      x: p1.x + (p2.x - p1.x) * t,
      y: p1.y + (p2.y - p1.y) * t
    })
  }
  return points
}

export function pointsToPath(points) {
  if (!points.length) return ''
  let d = `M ${points[0].x.toFixed(1)} ${points[0].y.toFixed(1)}`
  for (let i = 1; i < points.length; i++) {
    d += ` L ${points[i].x.toFixed(1)} ${points[i].y.toFixed(1)}`
  }
  return d
}